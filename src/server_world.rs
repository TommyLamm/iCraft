    /// Execute a villager offer atomically against a session's compact
    /// inventory.  Costs are checked before either item is removed and the
    /// complete state is restored if the sell stack cannot fit.
    pub fn apply_trade(
        &mut self,
        gameplay: &mut SessionGameplayState,
        villager_id: u64,
        offer_index: u16,
        player_position: [f32; 3],
    ) -> Result<(), RejectReason> {
        let Some(villager) = self.entities.get_by_id(villager_id) else {
            return Err(RejectReason::InvalidState);
        };
        if villager.entity_type != EntityType::Villager || villager.health <= 0.0 {
            return Err(RejectReason::InvalidState);
        }
        if villager
            .position
            .distance_squared(Vec3::from_array(player_position))
            > 8.0 * 8.0
        {
            return Err(RejectReason::TooFar);
        }
        let Some(offer) = villager.offers.get(usize::from(offer_index)).cloned() else {
            return Err(RejectReason::InvalidState);
        };
        if offer.is_out_of_stock() {
            return Err(RejectReason::InvalidState);
        }
        let cost_a = offer.effective_cost_a(0.0);
        let cost_b = offer.buy_b.map(|stack| stack.count).unwrap_or(0);
        let buy_a = offer.buy_a.item.to_u32();
        let buy_b = offer.buy_b.map(|stack| stack.item.to_u32());
        if gameplay.count_item(buy_a) < cost_a
            || buy_b.is_some_and(|item| gameplay.count_item(item) < cost_b)
        {
            return Err(RejectReason::InvalidState);
        }
        let original = *gameplay;
        let _ = gameplay.remove_item(buy_a, cost_a);
        if let Some(item) = buy_b {
            if !gameplay.remove_item(item, cost_b) {
                *gameplay = original;
                return Err(RejectReason::InvalidState);
            }
        }
        let sell = SessionInventorySlot::from_wire(
            crate::network::protocol::ItemWire::from_stack(&offer.sell),
            offer.sell.can_break,
            offer.sell.can_place_on,
        );
        if !gameplay.add_slot(sell) {
            *gameplay = original;
            return Err(RejectReason::InvalidState);
        }
        if (0..crate::authority::contract::SESSION_INVENTORY_SLOTS).any(|index| {
            transactions::brew_locks_slot(&original, index as u8)
                && original.inventory[index] != gameplay.inventory[index]
        }) {
            *gameplay = original;
            return Err(RejectReason::InvalidState);
        }
        let Some(villager) = self.entities.get_by_id_mut(villager_id) else {
            *gameplay = original;
            return Err(RejectReason::InvalidState);
        };
        let Some(offer) = villager.offers.get_mut(usize::from(offer_index)) else {
            *gameplay = original;
            return Err(RejectReason::InvalidState);
        };
        offer.uses = offer.uses.saturating_add(1);
        villager.villager_xp = villager.villager_xp.saturating_add(offer.xp_reward);
        Ok(())
    }

    /// Mount or dismount a player in the headless entity graph.  Entity
    /// passenger lists are authoritative; presentation roots only project the
    /// resulting `mounted_entity` session value.
    pub fn apply_mount(
        &mut self,
        player_id: PlayerId,
        entity_id: u64,
        player_position: [f32; 3],
    ) -> Result<Option<u64>, RejectReason> {
        if entity_id == 0 {
            for entity in &mut self.entities.entities {
                entity
                    .passengers
                    .retain(|passenger| *passenger != player_id);
            }
            return Ok(None);
        }
        let Some(vehicle) = self.entities.get_by_id(entity_id) else {
            return Err(RejectReason::InvalidState);
        };
        if !matches!(
            vehicle.entity_type,
            EntityType::Boat | EntityType::Minecart | EntityType::Horse
        ) {
            return Err(RejectReason::InvalidState);
        }
        if vehicle
            .position
            .distance_squared(Vec3::from_array(player_position))
            > 8.0 * 8.0
        {
            return Err(RejectReason::TooFar);
        }
        if vehicle.passengers.contains(&player_id) {
            return Ok(Some(entity_id));
        }
        let capacity = if vehicle.entity_type == EntityType::Boat {
            2
        } else {
            1
        };
        if vehicle.passengers.len() >= capacity {
            return Err(RejectReason::InvalidState);
        }
        for entity in &mut self.entities.entities {
            entity
                .passengers
                .retain(|passenger| *passenger != player_id);
        }
        let Some(vehicle) = self.entities.get_by_id_mut(entity_id) else {
            return Err(RejectReason::InvalidState);
        };
        vehicle.passengers.push(player_id);
        Ok(Some(entity_id))
    }

    fn ensure_container_slot(&self, x: i32, y: i32, z: i32, slot: u16) -> Result<(), RejectReason> {
        let Some(entity) = self.chunks.get_block_entity(x, y, z) else {
            return Err(RejectReason::InvalidState);
        };
        let Some(access) = ContainerAccess::for_entity(entity) else {
            return Err(RejectReason::InvalidState);
        };
        if usize::from(slot) >= access.slot_count {
            return Err(RejectReason::InvalidState);
        }
        Ok(())
    }

    pub fn open_container(
        &mut self,
        x: i32,
        y: i32,
        z: i32,
        slot: u16,
        player_id: PlayerId,
    ) -> Result<Option<WorldMutation>, RejectReason> {
        self.ensure_container_slot(x, y, z, slot)?;
        let position = (x, y, z);
        let container_positions = self.container_positions(position);
        let had_viewer = container_positions.iter().any(|position| {
            self.container_viewers
                .get(position)
                .is_some_and(|viewers| !viewers.is_empty())
        });
        for position in &container_positions {
            self.container_viewers
                .entry(*position)
                .or_default()
                .insert(player_id);
        }
        let state_mutation = if !had_viewer {
            self.set_chest_open_state(position, true)
        } else {
            None
        };
        Ok(Some(
            state_mutation.unwrap_or_else(|| self.touch_revision(x, y, z)),
        ))
    }

    pub fn close_container(
        &mut self,
        x: i32,
        y: i32,
        z: i32,
        slot: u16,
        player_id: PlayerId,
    ) -> Result<Option<WorldMutation>, RejectReason> {
        self.ensure_container_slot(x, y, z, slot)?;
        let position = (x, y, z);
        let container_positions = self.container_positions(position);
        let mut removed = false;
        for position in &container_positions {
            removed |= self.close_container_viewer(player_id, *position);
        }
        let has_viewer = container_positions.iter().any(|position| {
            self.container_viewers
                .get(position)
                .is_some_and(|viewers| !viewers.is_empty())
        });
        let state_mutation = if removed && !has_viewer {
            self.set_chest_open_state(position, false)
        } else {
            None
        };
        Ok(Some(
            state_mutation.unwrap_or_else(|| self.touch_revision(x, y, z)),
        ))
    }

    pub fn sleep_player(
        &mut self,
        x: i32,
        y: i32,
        z: i32,
        player_id: PlayerId,
    ) -> Result<Option<WorldMutation>, RejectReason> {
        if self.get_block(x, y, z) != BlockType::Bed {
            return Err(RejectReason::InvalidState);
        }
        if !self.sleeping_players.insert(player_id) {
            return Err(RejectReason::InvalidState);
        }
        Ok(Some(self.touch_revision(x, y, z)))
    }

    pub fn set_time(&mut self, time: u64) {
        self.time = time;
    }

    pub fn add_time(&mut self, time: u64) {
        self.time = self.time.wrapping_add(time);
    }

    pub fn set_gamerule(&mut self, rule: &str, value: Option<&str>) -> Result<(), RejectReason> {
        let Some(value) = value else {
            return Err(RejectReason::InvalidState);
        };
        if let Ok(bool_value) = value.parse::<bool>() {
            self.rules
                .set(rule, bool_value)
                .map_err(|_| RejectReason::InvalidState)?;
        } else if matches!(
            rule,
            "playerssleepingpercentage" | "sleepingpercentage" | "sleeping_percentage"
        ) {
            let percentage = value
                .parse::<u8>()
                .map_err(|_| RejectReason::InvalidState)?;
            self.rules.set_sleeping_percentage(percentage);
        } else {
            return Err(RejectReason::InvalidState);
        }
        Ok(())
    }

    /// Thin world dispatcher retained for `server_world` unit tests. Live
    /// requests go through `AuthorityCore`'s single operation match.
    #[cfg(test)]
    pub fn dispatch(
        &mut self,
        request: &GameplayRequest,
        player_id: PlayerId,
        _operator: bool,
    ) -> Result<Option<WorldMutation>, RejectReason> {
        match &request.operation {
            GameplayOperation::Container {
                action,
                x,
                y,
                z,
                slot,
            } => {
                let action =
                    ContainerAction::from_wire(*action).ok_or(RejectReason::InvalidState)?;
                match action {
                    ContainerAction::Open => self.open_container(*x, *y, *z, *slot, player_id),
                    ContainerAction::Close => self.close_container(*x, *y, *z, *slot, player_id),
                    ContainerAction::Click => {
                        self.ensure_container_slot(*x, *y, *z, *slot)?;
                        Err(RejectReason::Unsupported)
                    }
                }
            }
            GameplayOperation::ContainerClick { x, y, z, slot, .. } => {
                self.ensure_container_slot(*x, *y, *z, *slot)?;
                Err(RejectReason::Unsupported)
            }
            GameplayOperation::Sleep { x, y, z } => self.sleep_player(*x, *y, *z, player_id),
            GameplayOperation::Command { command } => {
                let parsed = commands::parse(command).map_err(|_| RejectReason::InvalidState)?;
                match parsed {
                    Command::GameRule { rule, value } => {
                        self.set_gamerule(&rule, value.as_deref())?;
                        Ok(None)
                    }
                    Command::Time(TimeCommand::Set(time)) => {
                        self.set_time(time);
                        Ok(None)
                    }
                    Command::Time(TimeCommand::Add(time)) => {
                        self.add_time(time);
                        Ok(None)
                    }
                    _ => Err(RejectReason::Unsupported),
                }
            }
            _ => Err(RejectReason::Unsupported),
        }
    }

    fn touch_revision(&mut self, x: i32, y: i32, z: i32) -> WorldMutation {
        let revision = self.revisions.allocate();
        self.block_revisions.insert((x, y, z), revision);
        self.chunk_revisions
            .insert((x.div_euclid(16), z.div_euclid(16)), revision);
        WorldMutation {
            dimension: self.dimension as u8,
            position: (x, y, z),
            block: self.get_block(x, y, z).to_wire(),
            state: self.get_block_state(x, y, z),
            raw_fluid: self.chunks.get_fluid_raw(x, y, z),
            revision,
        }
    }

    /// Record a fluid-only (or fluid-plus-block) mutation that has already
    /// been applied by the authoritative fluid carrier.  Fluid ticking writes
    /// directly to `ChunkManager` so it can schedule neighboring cells; this
    /// helper is the single revision/publication seam for that write.
    fn record_fluid_mutation(&mut self, mutation: FluidMutation) -> WorldMutation {
        let (x, y, z) = mutation.position;
        let revision = self.revisions.allocate();
        self.block_revisions.insert((x, y, z), revision);
        self.chunk_revisions
            .insert((x.div_euclid(16), z.div_euclid(16)), revision);
        WorldMutation {
            dimension: self.dimension as u8,
            position: mutation.position,
            block: mutation.block.to_wire(),
            state: self.get_block_state(x, y, z),
            raw_fluid: mutation.raw_fluid,
            revision,
        }
    }

    /// Advance exactly one 20 Hz tick.  All iteration order is normalized so
    /// the checksum and mutation revisions are topology-independent.
    pub fn tick(&mut self, players: &[(PlayerId, [f32; 3])]) -> AuthoritySnapshot {
        if self.rules.do_daylight_cycle {
            self.time = self.time.wrapping_add(1);
        }
        let mut mutations = Vec::new();

        let mut occupants: Vec<_> = players
            .iter()
            .filter_map(|(_, position)| {
                position.iter().all(|value| value.is_finite()).then_some((
                    position[0].floor() as i32,
                    position[1].floor() as i32,
                    position[2].floor() as i32,
                ))
            })
            .collect();
        occupants.sort_unstable();
        occupants.dedup();
        let simulation_distance = self.chunks.render_distance.clamp(0, 32) as u8;
        let mut simulation_chunks = BTreeSet::new();
        for (_, position) in players {
            if position.iter().all(|value| value.is_finite()) {
                simulation_chunks.extend(chunks_around(*position, simulation_distance));
            }
        }

        let redstone = self.redstone.tick(&mut self.chunks, &occupants);
        let mut redstone_mutations = redstone.mutations;
        self.pending_redstone_actions.extend(
            redstone
                .actions
                .into_iter()
                .filter(|action| matches!(action, RedstoneAction::Dispense { .. })),
        );
        redstone_mutations.sort_by_key(|mutation| mutation.pos);
        for mutation in redstone_mutations {
            if !self.column_in_set(&simulation_chunks, mutation.pos.0, mutation.pos.2) {
                continue;
            }
            if let Ok(Some(event)) = self.set_block(
                mutation.pos.0,
                mutation.pos.1,
                mutation.pos.2,
                mutation.new_block,
                0,
            ) {
                mutations.push(event);
            }
        }

        // These systems mutate actual block entities/chunks, not a shadow map.
        // Simulation-union only — do not call tick_all_loaded_*.
        let _ = crate::world_tick::tick_hoppers_in_columns(
            &mut self.chunks,
            Some(&mut self.entities),
            MAX_AUTOMATION_TRANSFERS,
            Some(&simulation_chunks),
        );
        for is_lava in [false, true] {
            let (_, fluid_mutations) = crate::fluid::tick_fluids_in_columns(
                &mut self.chunks,
                is_lava,
                MAX_FLUID_UPDATES,
                Some(&simulation_chunks),
            );
            for mutation in fluid_mutations {
                mutations.push(self.record_fluid_mutation(mutation));
            }
        }

        // Random ticks (crop growth, fire and leaf decay) run in the same
        // deterministic headless world as redstone/fluid automation.  The
        // renderer never performs a second random-tick pass for a boundary.
        let (mut random_ticks, _) = crate::world_tick::sample_random_ticks_in_columns(
            &self.chunks,
            Some(&simulation_chunks),
            self.seed as u64,
            self.time,
            self.dimension as u8,
            128,
        );
        if !self.rules.do_fire_tick {
            random_ticks.retain(|mutation| {
                self.get_block(mutation.pos.0, mutation.pos.1, mutation.pos.2) != BlockType::Fire
            });
        }
        random_ticks.sort_by_key(|mutation| mutation.pos);
        for mutation in random_ticks {
            if !self.column_in_set(&simulation_chunks, mutation.pos.0, mutation.pos.2) {
                continue;
            }
            if let Ok(Some(event)) = self.set_block(
                mutation.pos.0,
                mutation.pos.1,
                mutation.pos.2,
                mutation.new_block,
                mutation.new_state,
            ) {
                mutations.push(event);
            }
        }

        mutations.extend(self.tick_furnaces(&simulation_chunks));

        self.tick_entities(players);
        mutations.sort_by_key(|mutation| mutation.revision);
        let checksum = self.checksum(&mutations);
        AuthoritySnapshot {
            tick: self.time,
            revision: self.revisions.current(),
            checksum,
            mutations,
            session_updates: Vec::new(),
        }
    }

    /// Execute one authoritative dispenser/dropper edge with the candidate id
    /// supplied by AuthorityCore.  The method returns whether an entity was
    /// spawned; block/entity mutations are queued for the normal snapshot
    /// fanout. Invalid, unloaded, empty, or unsupported no-op cases consume
    /// nothing and produce no entity.
    pub fn execute_redstone_dispense(&mut self, action: RedstoneAction, entity_id: u64) -> bool {
        let RedstoneAction::Dispense {
            pos,
            facing,
            dropper,
        } = action
        else {
            return false;
        };
        let source_block = if dropper {
            BlockType::Dropper
        } else {
            BlockType::Dispenser
        };
        if !self.valid_coordinate(pos.0, pos.1, pos.2)
            || self.get_block(pos.0, pos.1, pos.2) != source_block
            || !self.chunks.is_block_loaded(pos.0, pos.1, pos.2)
        {
            return false;
        }
        let delta = facing.delta();
        let front = (pos.0 + delta.0, pos.1 + delta.1, pos.2 + delta.2);
        if !self.valid_coordinate(front.0, front.1, front.2)
            || !self.chunks.is_block_loaded(front.0, front.1, front.2)
        {
            return false;
        }
        let Some(source) = self.get_block_entity(pos.0, pos.1, pos.2).cloned() else {
            return false;
        };
        if !source.matches_block_type(source_block) {
            return false;
        }
        let seed = (self.seed as u64)
            ^ ((self.dimension as u8 as u64) << 56)
            ^ (pos.0 as i64 as u64).rotate_left(7)
            ^ (pos.1 as i64 as u64).rotate_left(19)
            ^ (pos.2 as i64 as u64).rotate_left(31)
            ^ self.redstone.current_tick();
        let Some(slot) = source.select_random_non_empty_slot(seed) else {
            return false;
        };
        let Some(stack) = source.get_stack(slot).copied() else {
            return false;
        };
        let one = crate::inventory::ItemStack { count: 1, ..stack };
        let spawn_pos = Vec3::new(
            pos.0 as f32 + 0.5 + delta.0 as f32 * 0.7,
            pos.1 as f32 + 0.5 + delta.1 as f32 * 0.7,
            pos.2 as f32 + 0.5 + delta.2 as f32 * 0.7,
        );
        let direction = Vec3::new(delta.0 as f32, delta.1 as f32, delta.2 as f32);

        let mut source_after = source.clone();
        let mut target_after = None;
        let mut spawn = None;
        let mut block_change = None;

        // Replace exactly one source item while preserving the remaining
        // stack.  Bucket items normally have max-stack one, but malformed or
        // legacy stacks are handled atomically instead of turning an entire
        // stack into filled buckets.
        let replace_one = |entity: &mut BlockEntity,
                           slot: usize,
                           original: crate::inventory::ItemStack,
                           replacement: crate::inventory::Item|
         -> bool {
            if original.count == 1 {
                entity.set_stack(
                    slot,
                    Some(crate::inventory::ItemStack {
                        item: replacement,
                        ..original
                    }),
                );
                true
            } else {
                entity.set_stack(
                    slot,
                    Some(crate::inventory::ItemStack {
                        count: original.count - 1,
                        ..original
                    }),
                );
                entity.try_insert_item(
                    None,
                    crate::inventory::ItemStack {
                        item: replacement,
                        count: 1,
                        ..original
                    },
                )
            }
        };

        if dropper {
            if let Some(target) = self.get_block_entity(front.0, front.1, front.2).cloned() {
                let mut candidate = target;
                if candidate.try_insert_item(Some(facing.opposite()), one) {
                    target_after = Some(candidate);
                }
            }
            if target_after.is_none() {
                spawn = Some((EntityType::DroppedItem, one, Vec3::new(0.0, 0.2, 0.0)));
            }
            source_after.set_stack(
                slot,
                (stack.count > 1).then_some(crate::inventory::ItemStack {
                    count: stack.count - 1,
                    ..stack
                }),
            );
        } else {
            match stack.item {
                crate::inventory::Item::Arrow => {
                    spawn = Some((EntityType::Arrow, one, direction * 18.0));
                    source_after.set_stack(
                        slot,
                        (stack.count > 1).then_some(crate::inventory::ItemStack {
                            count: stack.count - 1,
                            ..stack
                        }),
                    );
                }
                crate::inventory::Item::SplashPotion => {
                    spawn = Some((EntityType::SplashPotion, one, direction * 10.0));
                    source_after.set_stack(
                        slot,
                        (stack.count > 1).then_some(crate::inventory::ItemStack {
                            count: stack.count - 1,
                            ..stack
                        }),
                    );
                }
                crate::inventory::Item::Bucket => {
                    let filled = match self.get_block(front.0, front.1, front.2) {
                        BlockType::Water
                            if self.chunks.get_fluid_level(front.0, front.1, front.2) == 0
                                && !self.chunks.get_fluid_falling(front.0, front.1, front.2) =>
                        {
                            Some(crate::inventory::Item::WaterBucket)
                        }
                        BlockType::Lava
                            if self.chunks.get_fluid_level(front.0, front.1, front.2) == 0
                                && !self.chunks.get_fluid_falling(front.0, front.1, front.2) =>
                        {
                            Some(crate::inventory::Item::LavaBucket)
                        }
                        _ => None,
                    };
                    let Some(filled) = filled else {
                        return false;
                    };
                    block_change = Some(BlockType::Air);
                    if !replace_one(&mut source_after, slot, stack, filled) {
                        return false;
                    }
                }
                crate::inventory::Item::WaterBucket | crate::inventory::Item::LavaBucket => {
                    if self.get_block(front.0, front.1, front.2) != BlockType::Air {
                        return false;
                    }
                    block_change = Some(if stack.item == crate::inventory::Item::WaterBucket {
                        BlockType::Water
                    } else {
                        BlockType::Lava
                    });
                    if !replace_one(
                        &mut source_after,
                        slot,
                        stack,
                        crate::inventory::Item::Bucket,
                    ) {
                        return false;
                    }
                }
                crate::inventory::Item::FlintAndSteel => {
                    if self.get_block(front.0, front.1, front.2) != BlockType::Air
                        || !self
                            .get_block(front.0, front.1 - 1, front.2)
                            .properties()
                            .is_solid
                    {
                        return false;
                    }
                    block_change = Some(BlockType::Fire);
                    source_after.set_stack(
                        slot,
                        (stack.count > 1).then_some(crate::inventory::ItemStack {
                            count: stack.count - 1,
                            ..stack
                        }),
                    );
                }
                _ => {
                    spawn = Some((EntityType::DroppedItem, one, Vec3::new(0.0, 0.2, 0.0)));
                    source_after.set_stack(
                        slot,
                        (stack.count > 1).then_some(crate::inventory::ItemStack {
                            count: stack.count - 1,
                            ..stack
                        }),
                    );
                }
            }
        }

        // Validate the allocator candidate before committing any source,
        // target, or block mutation. A stale/invalid id must be a true no-op.
        if spawn.is_some() && (entity_id == 0 || self.entities.get_by_id(entity_id).is_some()) {
            return false;
        }

        // Commit all block-entity state only after the action has passed every
        // validation branch.  Each changed position receives one revision.
        self.chunks
            .set_block_entity(pos.0, pos.1, pos.2, Some(source_after));
        self.chunks.mark_block_entity_dirty(pos.0, pos.2);
        self.redstone.mark_container_changed(&self.chunks, pos);
        let source_mutation = self.touch_revision(pos.0, pos.1, pos.2);
        self.pending_mutations.push(source_mutation);

        if let Some(target) = target_after {
            self.chunks
                .set_block_entity(front.0, front.1, front.2, Some(target));
            self.chunks.mark_block_entity_dirty(front.0, front.2);
            self.redstone.mark_container_changed(&self.chunks, front);
            let target_mutation = self.touch_revision(front.0, front.1, front.2);
            self.pending_mutations.push(target_mutation);
        }
        if let Some(block) = block_change {
            let Ok(Some(mutation)) = self.set_block(front.0, front.1, front.2, block, 0) else {
                return false;
            };
            self.pending_mutations.push(mutation);
        }
        if let Some((entity_type, stack, velocity)) = spawn {
            let mut entity = crate::entity::Entity::new(entity_id, entity_type, spawn_pos);
            entity.velocity = velocity;
            match entity_type {
                EntityType::Arrow => {
                    entity.friendly_projectile = true;
                    entity.projectile_damage = 4.0;
                }
                EntityType::SplashPotion => entity.potion = stack.potion,
                EntityType::DroppedItem => {
                    entity.dropped_item = Some(stack.item);
                    entity.dropped_count = stack.count;
                    entity.dropped_stack = Some(stack);
                    entity.pickup_cooldown = 0.5;
                }
                _ => {}
            }
            self.entities.entities.push(entity);
            self.entities.rebuild_indexes();
            return true;
        }
        false
    }

    fn tick_furnaces(&mut self, simulation_chunks: &BTreeSet<(i32, i32)>) -> Vec<WorldMutation> {
        let mut positions = Vec::new();
        for &(cx, cz) in simulation_chunks {
            let Some(chunk) = self.chunks.chunks.get(&(cx, cz)) else {
                continue;
            };
            for (local, entity) in chunk.iter_block_entities() {
                if matches!(entity, BlockEntity::Furnace(_)) {
                    positions.push((
                        cx * 16 + local.0 as i32,
                        local.1 as i32,
                        cz * 16 + local.2 as i32,
                    ));
                }
            }
        }
        positions.sort_unstable();
        let mut mutations = Vec::new();
        for (x, y, z) in positions {
            let Some(BlockEntity::Furnace(furnace)) = self.chunks.get_block_entity_mut(x, y, z)
            else {
                continue;
            };
            let was_lit = furnace.is_lit;
            let result = furnace.tick(&self.recipe_manager);
            if !result.slot_changed && !result.lit_changed {
                continue;
            }
            furnace.revision = furnace.revision.wrapping_add(1);
            let is_lit = furnace.is_lit;
            let _ = furnace;
            if was_lit != is_lit {
                let block = if is_lit {
                    BlockType::FurnaceLit
                } else {
                    BlockType::Furnace
                };
                if let Ok(Some(event)) = self.set_block(x, y, z, block, 0) {
                    mutations.push(event);
                }
            } else {
                mutations.push(self.touch_revision(x, y, z));
            }
        }
        mutations
    }

    fn tick_entities(&mut self, players: &[(PlayerId, [f32; 3])]) {
        // Peaceful is an authority policy, not merely a spawn-rate hint:
        // already-loaded hostile entities are removed at the next fixed tick.
        // `do_mob_spawning=false` deliberately does not take this path, so it
        // cannot freeze an existing hostile entity's AI.
        if matches!(self.difficulty, ServerDifficulty::Peaceful) {
            let before = self.entities.entities.len();
            self.entities
                .entities
                .retain(|entity| !entity.entity_type.is_hostile());
            if self.entities.entities.len() != before {
                self.entities.rebuild_indexes();
            }
        }
        let mut player_positions: Vec<_> = players.to_vec();
        player_positions.sort_by_key(|(id, _)| *id);
        if self.rules.do_mob_spawning && self.dimension == Dimension::Overworld {
            for (_, position) in &player_positions {
                let player = Vec3::from_array(*position);
                let sky_light = if (self.time % 24_000) < 12_000 { 15 } else { 4 };
                crate::passive_mob::spawn_passive_mobs(
                    &mut self.entities,
                    &self.chunks,
                    player,
                    sky_light,
                    self.time as f32 * FIXED_DT,
                );
                if self.allows_hostile_spawning() {
                    crate::mob::spawn_mobs(
                        &mut self.entities,
                        &self.chunks,
                        player,
                        sky_light,
                        self.time as f32 * FIXED_DT,
                    );
                }
            }
        }
        let chunks = &self.chunks;
        for entity in &mut self.entities.entities {
            if entity.entity_type == EntityType::FishingHook {
                continue;
            }
            entity.action_cooldown = (entity.action_cooldown - FIXED_DT).max(0.0);
            entity.invulnerable_time = (entity.invulnerable_time - FIXED_DT).max(0.0);
            entity.fire_aspect_timer = (entity.fire_aspect_timer - FIXED_DT).max(0.0);
            if entity.entity_type.is_hostile()
                && !matches!(self.difficulty, ServerDifficulty::Peaceful)
            {
                if let Some((_, target)) =
                    player_positions.iter().min_by(|(_, left), (_, right)| {
                        entity
                            .position
                            .distance_squared(Vec3::from_array(*left))
                            .total_cmp(&entity.position.distance_squared(Vec3::from_array(*right)))
                    })
                {
                    let direction =
                        (Vec3::from_array(*target) - entity.position).normalize_or_zero();
                    let speed = self.difficulty.hostile_chase_speed_milli() as f32 / 1_000.0;
                    entity.velocity.x = direction.x * 1.2 * speed;
                    entity.velocity.z = direction.z * 1.2 * speed;
                    entity.target_player = true;
                }
            }
            entity.ai_phase = entity.ai_phase.wrapping_add(1);
            entity.ai_timer += FIXED_DT;
            entity.update_physics(FIXED_DT, chunks);
        }
        self.entities.sync_positions();

        if let Some((_, first_pos)) = player_positions.first() {
            let player_vec = Vec3::from_array(*first_pos);
            crate::boss::ensure_dimension_entities(
                self.dimension,
                &mut self.entities,
                &self.chunks,
                player_vec,
                self.time as f32 * FIXED_DT,
            );
            let boss_events = crate::boss::update_dimension_entities(
                self.dimension,
                &mut self.entities,
                &self.chunks,
                player_vec,
                Vec3::NEG_Z,
                FIXED_DT,
                crate::inventory::GameMode::Survival,
            );
            if boss_events.dragon_completion.is_some() {
                self.handle_dragon_completion();
            }
        }
    }

